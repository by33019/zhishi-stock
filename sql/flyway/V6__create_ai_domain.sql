CREATE TABLE `ai_feedback` (
  `id` bigint NOT NULL COMMENT '反馈 ID，由应用生成',
  `report_id` bigint NOT NULL COMMENT '报告 ID，应用层维护关联',
  `user_id` bigint NOT NULL COMMENT '反馈用户 ID',
  `feedback_type` varchar(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'HELPFUL 或 NOT_HELPFUL',
  `reason_code` varchar(32) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL COMMENT 'FACT_ERROR、CITATION_ERROR、OVER_INFERENCE、OFF_TOPIC 或 OUTDATED',
  `detail` varchar(600) DEFAULT NULL COMMENT '应用限制最多 300 字符',
  `created_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE INDEX `uk_ai_feedback_report_user` (`report_id`, `user_id`),
  INDEX `idx_ai_feedback_user_time` (`user_id`, `updated_at` DESC),
  INDEX `idx_ai_feedback_type_reason` (`feedback_type`, `reason_code`, `updated_at`),
  CONSTRAINT `ck_ai_feedback_type` CHECK (`feedback_type` IN ('HELPFUL', 'NOT_HELPFUL')),
  CONSTRAINT `ck_ai_feedback_reason` CHECK (`reason_code` IS NULL OR `reason_code` IN ('FACT_ERROR', 'CITATION_ERROR', 'OVER_INFERENCE', 'OFF_TOPIC', 'OUTDATED')),
  CONSTRAINT `ck_ai_feedback_detail` CHECK (`detail` IS NULL OR CHAR_LENGTH(`detail`) <= 300)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4 COLLATE=utf8mb4_general_ci ROW_FORMAT=DYNAMIC COMMENT='用户对 AI 报告的反馈';

CREATE TABLE `ai_usage` (
  `id` bigint NOT NULL COMMENT '调用用量 ID，由应用生成',
  `task_id` bigint NOT NULL COMMENT 'AI 任务 ID，每次实际 Provider 调用一条记录',
  `attempt_no` tinyint unsigned NOT NULL COMMENT '对应任务执行次数',
  `user_id` bigint NOT NULL COMMENT '用户 ID，冗余用于配额与成本汇总',
  `provider_code` varchar(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `model_code` varchar(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `provider_request_id` varchar(191) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `prompt_tokens` int unsigned NOT NULL DEFAULT 0,
  `completion_tokens` int unsigned NOT NULL DEFAULT 0,
  `cached_tokens` int unsigned NOT NULL DEFAULT 0,
  `total_tokens` int unsigned NOT NULL DEFAULT 0,
  `estimated_cost` decimal(18,8) NOT NULL DEFAULT 0 COMMENT '内部成本估算，不直接面向用户',
  `currency_code` char(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'CNY',
  `first_chunk_latency_ms` int unsigned DEFAULT NULL,
  `total_latency_ms` int unsigned DEFAULT NULL,
  `result_status` varchar(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'SUCCESS、FAILURE、CANCELED 或 TIMED_OUT',
  `error_category` varchar(32) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `call_started_at` datetime(3) NOT NULL,
  `call_completed_at` datetime(3) DEFAULT NULL,
  `created_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE INDEX `uk_ai_usage_task_attempt` (`task_id`, `attempt_no`),
  INDEX `idx_ai_usage_user_time` (`user_id`, `call_started_at` DESC),
  INDEX `idx_ai_usage_provider_time` (`provider_code`, `model_code`, `call_started_at` DESC),
  INDEX `idx_ai_usage_status_time` (`result_status`, `call_started_at` DESC),
  CONSTRAINT `ck_ai_usage_attempt` CHECK (`attempt_no` >= 1),
  CONSTRAINT `ck_ai_usage_status` CHECK (`result_status` IN ('SUCCESS', 'FAILURE', 'CANCELED', 'TIMED_OUT')),
  CONSTRAINT `ck_ai_usage_tokens` CHECK (`total_tokens` >= `prompt_tokens` + `completion_tokens`),
  CONSTRAINT `ck_ai_usage_period` CHECK (`call_completed_at` IS NULL OR `call_completed_at` >= `call_started_at`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4 COLLATE=utf8mb4_general_ci ROW_FORMAT=DYNAMIC COMMENT='大模型调用用量与成本';
