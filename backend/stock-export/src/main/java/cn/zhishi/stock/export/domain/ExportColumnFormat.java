package cn.zhishi.stock.export.domain;

/**
 * 一列在文件里的呈现口径。
 *
 * <h2>为什么列必须有"格式"，而不是只看单元格的值类型</h2>
 * 取值类型（{@link ExportCell.Text} / {@link ExportCell.Decimal}）只回答"是不是数字"，
 * 回答不了"这个数字该怎么显示"。而契约 §4.2 把行情字段定义成**十进制定点字符串**，
 * 其中涨跌幅与换手率是**小数形式的比率**：
 * {@code "0.0300"} 的含义是 3%，页面按 {@code ×100} 渲染成 {@code +3.00%}。
 * 若文件里原样写 {@code 0.03}，用户会读成 0.03%——一个整整差 100 倍的误读，
 * 而它在文件里没有任何异常、打开也看不出问题。
 *
 * <p>因此比率的列写成"值为 0.03、单元格格式为百分比"的**数值**单元格：
 * Excel 显示 {@code 3.00%}，且求和、排序都仍然可用。
 * 把它写成文本 {@code "3.00%"} 就丧失了可计算性——一个行情导出文件不能求和是更大的损失。
 *
 * <h2>为什么不用"按列 key 判断"</h2>
 * 格式跟着列定义走（见 {@link StockRankingColumn}），因此列白名单、表头、
 * 取值函数、显示格式四件事在同一个常量上，改动漏掉任何一项都会被编译期或单测发现。
 */
public enum ExportColumnFormat {

    /** 文本：左对齐，原样写出。 */
    TEXT,

    /** 价格/涨跌额：两位小数。 */
    PRICE,

    /** 量额：千分位整数。成交量与成交额都是整数，保留小数位只会带来无意义的噪声。 */
    AMOUNT,

    /** 比率：值本身是小数（{@code 0.0300}），按百分比显示（{@code 3.00%}）。 */
    PERCENT
}
