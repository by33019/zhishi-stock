package cn.zhishi.stock.admin.domain;

/**
 * 把已写好 {@code RUNNING} 记录的执行交给后台线程。
 *
 * <h2>为什么人工触发必须真的异步</h2>
 * 契约 ADM-JOB-02 要求返回 **202 Accepted**（"已接受、尚未处理完"）。同步跑完再返回 202
 * 是让状态码说谎：调用方据此以为可以稍后轮询，而实际上任务已经结束了一分钟。
 * 资讯采集一轮要几秒到几十秒，行情采集也要连 Provider——把它们挂在 HTTP 请求上，
 * 还会让"管理员点了按钮之后浏览器一直转圈"成为常态。
 *
 * <h2>为什么"先写记录再提交"的顺序不能反</h2>
 * 记录必须先落库（{@code RUNNING}），提交到线程池之后响应才能带着真实的
 * {@code executionId} 返回。反过来（先在后台线程里建记录）会出现一个窗口：
 * 响应已经返回，调用方立刻去查却查不到——那是最容易被当成"接口没生效"的现象。
 *
 * <h2>提交被拒时要回填</h2>
 * 队列满或线程池已关闭时 {@code submit} 会抛异常。此时那条 {@code RUNNING} 记录
 * 会永远停在运行中，而"卡住的任务"正是运维最需要准确的一个信号。
 * 因此用例层在提交失败时把它回填成 FAILED。
 */
public interface JobExecutionDispatcher {

    /**
     * 提交一次执行。实现方必须**立即返回**，任务的执行发生在别的线程上。
     *
     * @throws RuntimeException 队列满或执行器不可用；调用方负责回填记录
     */
    void submit(Runnable task);
}
